// Writes the "Listed plugins" and "Listed themes" tables in README.md from plugins.json and themes.json.
// Run: bun scripts/readme.ts        (validate.ts fails when the README is out of date: run this, then commit)
const perm = (p: any): string => {
  const out: string[] = [];
  if (p?.network?.length) out.push(`network: ${p.network.join(", ")}`);
  if (p?.shell) out.push("shell");
  if (p?.keyboard) out.push("keyboard");
  if (p?.storage) out.push("storage");
  if (p?.onair) out.push("On Air");
  return out.join(", ") || "none";
};
const local = (repo: string) => { const m = /\/tree\/[^/]+\/((?:plugins|themes)\/[^/]+)\/?$/.exec(repo); return m ? m[1] : repo; };
export async function tables(): Promise<string> {
  const plugins = JSON.parse(await Bun.file("plugins.json").text());
  const themes = JSON.parse(await Bun.file("themes.json").text());
  const p = plugins.map((x: any) => `| [${x.name}](${local(x.repo)}) | ${x.version} | ${x.description} | ${perm(x.permissions)} |`).join("\n");
  const t = themes.map((x: any) => `| [${x.name}](${local(x.repo)}) | ${x.variants.map((v: any) => v.name).join(", ")} | ${x.license ?? ""} | ${x.credit ?? ""} |`).join("\n");
  return `<!-- listed:start (generated by scripts/readme.ts from plugins.json and themes.json; do not edit by hand) -->
## Listed plugins

Browse them with previews at [nookdeck.app/plugins](https://nookdeck.app/plugins), or in Nookdeck under **Plugins** → **Discover**.

| Plugin | Version | What it does | Permissions |
|---|---|---|---|
${p}

## Listed themes

Browse them at [nookdeck.app/themes](https://nookdeck.app/themes), or in Nookdeck under **Theme** → **Packs**. Themes need Nookdeck 0.4.0 or later. Nookdeck and Nookdeck Classic ship inside the app.

| Theme | Variants | Licence | Credit |
|---|---|---|---|
${t}
<!-- listed:end -->`;
}
export async function expectedReadme(): Promise<string> {
  const s = await Bun.file("README.md").text();
  const a = s.indexOf("<!-- listed:start"), b = s.indexOf("<!-- listed:end -->");
  if (a < 0 || b < 0) throw new Error("README.md has no listed:start / listed:end markers");
  return s.slice(0, a) + (await tables()) + s.slice(b + "<!-- listed:end -->".length);
}
if (import.meta.main) { await Bun.write("README.md", await expectedReadme()); console.log("README.md updated"); }
